"""Generate finite-volume polynomial maps with exact rational arithmetic (SymPy)."""
import json
from pathlib import Path
import sympy as s
z=s.symbols('z'); half=s.Rational(1,2)
def moment(k,j): return ((s.Rational(j)+half)**(k+1)-(s.Rational(j)-half)**(k+1))/(k+1)
def kernel(offsets):
 n=len(offsets);A=s.Matrix([[moment(k,j) for k in range(n)] for j in offsets]);B=A.inv();assert A*B==s.eye(n)
 face=(s.Matrix([[half**k for k in range(n)]])*B)
 return {'offsets':offsets,'matrix':[[float(x) for x in row] for row in B.tolist()],'face':[float(x) for x in face],'faceTex':[s.latex(x) for x in face]}
def indicator(degree):
 H=s.zeros(degree)
 for l in range(1,degree+1):
  for a in range(l,degree+1):
   for b in range(l,degree+1):
    H[a-1,b-1]+=s.factorial(a)/s.factorial(a-l)*s.factorial(b)/s.factorial(b-l)*s.integrate(z**(a+b-2*l),(z,-half,half))
 L,D=H.LDLdecomposition(hermitian=False);assert L*D*L.T==H
 return {'L':[[float(v) for v in row] for row in L.tolist()],'D':[float(D[i,i]) for i in range(degree)]}
tables={};specs={}
for r in [3,4,5]:
 offs=list(range(1-r,r));ks=[list(range(1-r+k,k+1)) for k in range(r)]
 F=s.zeros(2*r-1,r)
 for k,sub in enumerate(ks):
  B=s.Matrix([[moment(j,o) for j in range(r)] for o in sub]).inv()
  f=s.Matrix([[half**j for j in range(r)]])*B
  for o,a in zip(sub,f):F[offs.index(o),k]=a
 target=s.Matrix([[moment(j,o) for j in range(2*r-1)] for o in offs]).inv().T*s.Matrix([half**j for j in range(2*r-1)])
 weights=list(s.linsolve((F,target)))[0];assert F*s.Matrix(weights)==target
 specs[f'wenojs{2*r-1}']={'offsets':offs,'candidates':ks,'optimal':[float(x) for x in weights],'optimalTex':[s.latex(x) for x in weights],'degree':r-1}
 for sub in ks+[offs]:tables[','.join(map(str,sub))]=kernel(sub)
 print(f'WENO{2*r-1} exact weights:',weights)
# TENO6 Table1/5, reordered left/central/right/wide-right.
offs=[-2,-1,0,1,2,3];ks=[[-2,-1,0],[-1,0,1],[0,1,2],[0,1,2,3]];weights=[s.Rational(1,20),s.Rational(9,20),s.Rational(3,10),s.Rational(1,5)]
for sub in ks+[offs]:tables[','.join(map(str,sub))]=kernel(sub)
for degree in range(6):
 actual=0
 for sub,w in zip(ks,weights):
  B=s.Matrix([[moment(j,o) for j in range(len(sub))] for o in sub]).inv()
  actual+=w*(s.Matrix([[half**j for j in range(len(sub))]])*B*s.Matrix([moment(degree,o) for o in sub]))[0]
 assert s.simplify(actual-half**degree)==0
# Published beta6 (Fu Eq18) is the JS derivative integral of the full polynomial.
B=s.Matrix([[moment(j,o) for j in range(6)] for o in offs]).inv()
P=sum((B*s.Matrix(s.symbols('v:6')))[j]*z**j for j in range(6))
beta=s.expand(sum(s.integrate(s.diff(P,z,l)**2,(z,-half,half)) for l in range(1,6)))
v=s.symbols('v:6'); expected=[271779,5653317,19510972,17195652,3824847,139633]
assert [beta.coeff(x,2)*120960 for x in v]==expected
cross=[-2380800,4086352,-3462252,1458762,-245620,-20427884,17905032,-7727988,1325006,-35817664,15929912,-2792660,-15880404,2863984,-1429976]
assert [beta.coeff(v[i],1).coeff(v[j],1)*120960 for i in range(6) for j in range(i+1,6)]==cross
specs['teno6']={'offsets':offs,'candidates':ks,'optimal':[float(x) for x in weights],'optimalTex':[s.latex(x) for x in weights],'degree':3}
output={'kernels':tables,'indicators':{str(d):indicator(d) for d in range(1,9)},'schemes':specs}
path=Path(__file__).resolve().parents[1]/'static/outreach/riemann-lab/reconstruction-tables.mjs'
path.write_text('// Generated by scripts/generate-reconstruction-tables.py; exact moment identities checked there.\nexport const TABLES = '+json.dumps(output,separators=(',',':'))+';\n')
print('Verified polynomial moments, optimal face degrees, positive indicator factors and all published beta6 coefficients.')
